#!/usr/bin/env node
/**
 * Generate Language Names
 *
 * This script writes `themes/base/data/languages.yaml`, a table from
 * three-letter language codes (ISO 639-2 style: `spa`, `eng`, `que`) to
 * the language's name in each language the engine ships (English and
 * Spanish). A repository record's `description_language` is such a code,
 * and the repository page shows the name in the site's language from this
 * file.
 *
 * It is run by hand when the table needs refreshing, not as part of a
 * build: `node scripts/generate-language-names.js`. The names come from
 * the Unicode CLDR data that ships inside Node, through
 * `Intl.DisplayNames`, so the output depends on the Node version that ran
 * it; the file header records that version and its CLDR and ICU versions.
 * The English names use the `en-US` locale and the Spanish names `es-CO`.
 *
 * The code list is every three-letter code from `aaa` to `zzz` for which
 * `Intl.DisplayNames` in `en-US` returns a name. CLDR names about 740 of
 * them. A code that has an English name but no Spanish one is written
 * with its `en` entry only; the reader falls back to the code or to the
 * English name, and the script never supplies a Spanish name itself.
 *
 * @version v1.6.0
 */

'use strict';

const fs = require('fs');
const path = require('path');

const LANGUAGES = { en: 'en-US', es: 'es-CO' };
const LETTERS = 'abcdefghijklmnopqrstuvwxyz';

/**
 * Returns { code: { en, es? } } sorted by code. `es` is absent when CLDR
 * has no Spanish name for the code.
 */
function buildLanguages() {
  const namers = Object.fromEntries(
    Object.entries(LANGUAGES).map(([key, locale]) => [key, new Intl.DisplayNames([locale], { type: 'language', fallback: 'none' })])
  );
  const nameOf = (key, code) => {
    try {
      return namers[key].of(code) || null;
    } catch (e) {
      return null; // RangeError for a code the locale data does not accept
    }
  };
  const out = {};
  for (const a of LETTERS) {
    for (const b of LETTERS) {
      for (const c of LETTERS) {
        const code = a + b + c;
        const en = nameOf('en', code);
        if (!en) continue;
        const entry = { en };
        const es = nameOf('es', code);
        if (es) entry.es = es;
        out[code] = entry;
      }
    }
  }
  return out;
}

function renderYaml(languages) {
  const v = process.versions;
  const lines = [
    '# Language names — three-letter codes',
    '#',
    '# Every three-letter language code (aaa-zzz) that CLDR names in English,',
    '# with the name in each language the engine ships. A repository',
    '# record\'s description_language (e.g. spa) is looked up here to show the',
    '# language in the site\'s language. A code with no Spanish name in CLDR',
    '# has an en entry only.',
    '#',
    '# Generated by scripts/generate-language-names.js; do not edit by hand.',
    `# Names: Unicode CLDR ${v.cldr} via Intl.DisplayNames (Node ${v.node}, ICU ${v.icu}),`,
    `# locales ${Object.entries(LANGUAGES).map(([k, l]) => `${k}=${l}`).join(', ')}.`,
    '#',
    '# Version: v1.6.0',
    '',
  ];
  for (const [code, entry] of Object.entries(languages)) {
    lines.push(`${code}:`);
    for (const key of Object.keys(LANGUAGES)) {
      if (entry[key]) lines.push(`  ${key}: ${JSON.stringify(entry[key])}`);
    }
  }
  lines.push('');
  lines.push('# Version: v1.6.0');
  return lines.join('\n') + '\n';
}

if (require.main === module) {
  const target = path.join(__dirname, '..', 'themes', 'base', 'data', 'languages.yaml');
  fs.writeFileSync(target, renderYaml(buildLanguages()));
  console.log(`[generate-language-names] wrote ${path.relative(process.cwd(), target)}`);
}

module.exports = { LANGUAGES, buildLanguages, renderYaml };

// Version: v1.6.0
